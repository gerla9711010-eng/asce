def R(code, pt, *kws, first=True):
    """用關鍵字找出契約第 pt 點裡含有關鍵字的行，組成引用字串（避免手數行號）"""
    ls = _m.arts(code)[f'第{pt}條']
    idx = [i for i, l in enumerate(ls, 1) if any(k in l for k in kws)]
    assert idx, f'{code} 第{pt}點 找不到 {kws}'
    if first and 1 not in idx:
        idx = [1] + idx
    return f'{code} {pt}#' + ','.join(map(str, idx))

